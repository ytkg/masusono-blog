import { act, fireEvent, render, screen } from "@testing-library/react"
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest"
import MasudaTatakiGame from "./MasudaTatakiGame"
import { loadImages } from "./assets"
import { AppActivityProvider } from "../shared/AppActivityContext"
vi.mock("./assets", () => ({ IMAGES: ["/masuda.webp", "/other1.webp", "/other2.webp"], loadImages: vi.fn() }))
describe("増田たたきの進行", () => {
  beforeEach(() => {
    vi.useFakeTimers()
    loadImages.mockResolvedValue([])
    vi.spyOn(Math, "random").mockReturnValue(0)
  })
  afterEach(() => {
    vi.useRealTimers()
    vi.restoreAllMocks()
  })
  const ready = async () => {
    await act(async () => {})
  }
  const advance = (ms) => act(() => vi.advanceTimersByTime(ms))
  it("非表示タブではカウントダウン・持ち時間・採点を止め、同じ状態から再開する", async () => {
    const visibility = vi.spyOn(document, "visibilityState", "get").mockReturnValue("visible")
    const changeVisibility = (state) => {
      visibility.mockReturnValue(state)
      act(() => document.dispatchEvent(new Event("visibilitychange")))
    }
    render(<MasudaTatakiGame />)
    await ready()
    fireEvent.click(screen.getByRole("button", { name: "スタート" }))
    advance(1500)
    changeVisibility("hidden")
    advance(30000)
    expect(screen.getByRole("status")).toHaveTextContent("2")
    changeVisibility("visible")
    advance(1500)
    advance(30)
    const target = screen.getByRole("button", { name: "穴1 増田" })
    changeVisibility("hidden")
    advance(30000)
    fireEvent.pointerDown(target)
    expect(screen.getByText("残り 30秒")).toBeInTheDocument()
    expect(screen.getByText("0点")).toBeInTheDocument()
    changeVisibility("visible")
    fireEvent.pointerDown(target)
    expect(screen.getByText("100点")).toBeInTheDocument()
    advance(30000)
    expect(screen.getByRole("status")).toHaveTextContent("TIME UP!")
    changeVisibility("hidden")
    advance(10000)
    expect(screen.getByRole("status")).toHaveTextContent("TIME UP!")
    changeVisibility("visible")
    advance(1000)
    expect(screen.getByText("増田ヒット数：1")).toBeInTheDocument()
  })

  it("最初の描画前の空穴タップでは採点せず、表示後に同じ穴を叩くと採点する", async () => {
    render(<MasudaTatakiGame />)
    await ready()
    fireEvent.click(screen.getByRole("button", { name: "スタート" }))
    advance(3000)
    expect(screen.getByRole("button", { name: "穴1", exact: true })).toBeInTheDocument()
    fireEvent.pointerDown(screen.getByRole("button", { name: "穴1", exact: true }))
    expect(screen.getByText("0点")).toBeInTheDocument()
    fireEvent.pointerDown(screen.getByRole("button", { name: "穴1 増田", exact: true }))
    expect(screen.getByText("100点")).toBeInTheDocument()
    fireEvent.pointerDown(screen.getByRole("button", { name: "穴1", exact: true }))
    expect(screen.getByText("100点")).toBeInTheDocument()
  })

  it("タップ時に期限切れから入れ替わったキャラクターは次の操作から採点する", async () => {
    render(<MasudaTatakiGame />)
    await ready()
    fireEvent.click(screen.getByRole("button", { name: "スタート" }))
    advance(3000)
    advance(30)
    const target = screen.getByRole("button", { name: "穴1 増田", exact: true })
    vi.spyOn(performance, "now").mockReturnValue(performance.now() + 2000)
    fireEvent.pointerDown(target)
    expect(screen.getByText("0点")).toBeInTheDocument()
    fireEvent.pointerDown(screen.getByRole("button", { name: "穴1 増田", exact: true }))
    expect(screen.getByText("100点")).toBeInTheDocument()
  })

  it("画像読み込み後に開始、カウントダウン、連打防止、結果、再プレイ", async () => {
    render(<MasudaTatakiGame />)
    await ready()
    fireEvent.click(screen.getByRole("button", { name: "スタート" }))
    expect(screen.getByRole("status")).toHaveTextContent("3")
    advance(1000)
    expect(screen.getByRole("status")).toHaveTextContent("2")
    advance(2000)
    advance(30)
    const target = screen.getByRole("button", { name: "穴1 増田" })
    fireEvent.pointerDown(target)
    fireEvent.pointerDown(target)
    expect(screen.getByText("100点")).toBeInTheDocument()
    expect(screen.getByText("1コンボ ×1.0")).toBeInTheDocument()
    advance(900)
    fireEvent.pointerDown(screen.getByRole("button", { name: "穴1 増田" }))
    expect(screen.getByText("210点")).toBeInTheDocument()
    expect(screen.getByText("2コンボ ×1.1")).toHaveStyle({ fontWeight: "900" })
    advance(30000)
    expect(screen.getByRole("status")).toHaveTextContent("TIME UP!")
    advance(1000)
    expect(screen.getByText("増田ヒット数：2")).toBeInTheDocument()
    expect(screen.getByText("最大コンボ：2")).toBeInTheDocument()
    fireEvent.click(screen.getByRole("button", { name: "もう一度遊ぶ" }))
    expect(screen.getByRole("status")).toHaveTextContent("3")
    expect(screen.getByText("0点")).toBeInTheDocument()
  })
  it("画像の失敗時は再試行し、読み込むまで開始しない", async () => {
    loadImages.mockRejectedValueOnce(new Error("offline"))
    render(<MasudaTatakiGame />)
    expect(screen.getByRole("button", { name: "画像を読み込み中…" })).toBeDisabled()
    await ready()
    expect(screen.getByRole("alert")).toBeInTheDocument()
    fireEvent.click(screen.getByRole("button", { name: "再読み込み" }))
    await ready()
    expect(screen.getByRole("button", { name: "スタート" })).toBeEnabled()
  })
  it("閉じると進行が止まり、アンマウント時にタイマーを解除", async () => {
    const { rerender, unmount } = render(<MasudaTatakiGame active />)
    await ready()
    fireEvent.click(screen.getByRole("button", { name: "スタート" }))
    advance(3000)
    advance(3000)
    rerender(<MasudaTatakiGame active={false} />)
    advance(30000)
    expect(screen.getByText("残り 27秒")).toBeInTheDocument()
    unmount()
    expect(vi.getTimerCount()).toBe(0)
  })
  it("カウントダウンを一時停止して再開しても3秒へ戻らない", async () => {
    const { rerender } = render(<MasudaTatakiGame active />)
    await ready()
    fireEvent.click(screen.getByRole("button", { name: "スタート" }))
    advance(1500)
    expect(screen.getByRole("status")).toHaveTextContent("2")
    rerender(<MasudaTatakiGame active={false} />)
    advance(10000)
    expect(screen.getByRole("status")).toHaveTextContent("2")
    rerender(<MasudaTatakiGame active />)
    advance(1499)
    expect(screen.getByRole("status")).toHaveTextContent("1")
    advance(1)
    expect(screen.queryByRole("status")).not.toBeInTheDocument()
  })

  it("ダイアログが操作不可の間は開始できず、進行中のカウントダウンも止める", async () => {
    const game = (active) => (
      <AppActivityProvider value={active}>
        <MasudaTatakiGame />
      </AppActivityProvider>
    )
    const { rerender } = render(game(false))
    await ready()
    fireEvent.click(screen.getByRole("button", { name: "スタート" }))
    expect(screen.getByRole("button", { name: "スタート" })).toBeInTheDocument()
    rerender(game(true))
    fireEvent.click(screen.getByRole("button", { name: "スタート" }))
    advance(1500)
    expect(screen.getByRole("status")).toHaveTextContent("2")
    rerender(game(false))
    advance(10000)
    expect(screen.getByRole("status")).toHaveTextContent("2")
    rerender(game(true))
    advance(1500)
    expect(screen.queryByRole("status")).not.toBeInTheDocument()
    advance(30)
    rerender(game(false))
    const target = screen.getByRole("button", { name: "穴1 増田" })
    fireEvent.pointerDown(target)
    advance(30000)
    expect(screen.getByText("0点")).toBeInTheDocument()
    expect(screen.getByText("残り 30秒")).toBeInTheDocument()
    rerender(game(true))
    fireEvent.pointerDown(target)
    expect(screen.getByText("100点")).toBeInTheDocument()
  })
})
